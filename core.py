"""Prototipo educativo Lambda/Kappa. Un solo escritor de ingesta.
El log es duradero y append-only a través de la aplicación; no se usa Kafka.
SQLite = evaluación local; PostgreSQL = despliegue Docker.
"""
import os, random, threading
from contextlib import contextmanager
from datetime import date,timedelta
from sqlalchemy import create_engine,text

URL=os.getenv('DATABASE_URL','sqlite:///./data/lab.db')
engine=create_engine(URL, **({'connect_args':{'check_same_thread':False,'timeout':60}} if URL.startswith('sqlite') else {}))
MODES=('lambda','kappa')
_write_lock=threading.RLock()
@contextmanager
def write():
    # One writer per process avoids SQLite read-to-write upgrade races.
    with _write_lock:
        with engine.begin() as conn:
            yield conn

def init():
    identity='INTEGER PRIMARY KEY AUTOINCREMENT' if engine.dialect.name=='sqlite' else 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    with write() as c:
        if engine.dialect.name=='sqlite': c.execute(text('PRAGMA journal_mode=WAL'))
        c.execute(text(f'''CREATE TABLE IF NOT EXISTS events (
        seq {identity}, event_id TEXT UNIQUE NOT NULL, plate TEXT NOT NULL,
        day TEXT NOT NULL, odometer BIGINT NOT NULL, gallons_milli BIGINT NOT NULL,
        cost_cents BIGINT NOT NULL)'''))
        c.execute(text('CREATE INDEX IF NOT EXISTS events_plate_day ON events(plate,day)'))
        c.execute(text('CREATE TABLE IF NOT EXISTS checkpoints (mode TEXT PRIMARY KEY, offset_seq BIGINT NOT NULL, watermark BIGINT NOT NULL)'))
        for mode in MODES:
            c.execute(text('INSERT INTO checkpoints VALUES (:m,0,0) ON CONFLICT(mode) DO NOTHING'),{'m':mode})
        for t in ('lambda_batch','kappa_totals'):
            c.execute(text(f'''CREATE TABLE IF NOT EXISTS {t} (plate TEXT, day TEXT, n BIGINT NOT NULL,
            gallons_milli BIGINT NOT NULL,cost_cents BIGINT NOT NULL,PRIMARY KEY(plate,day))'''))
        c.execute(text('''CREATE TABLE IF NOT EXISTS lambda_speed (seq BIGINT PRIMARY KEY,plate TEXT NOT NULL,
        day TEXT NOT NULL,gallons_milli BIGINT NOT NULL,cost_cents BIGINT NOT NULL)'''))

def reset():
    """Destructivo SOLO para datos de este laboratorio. No apuntar a una BD real."""
    with write() as c:
        for table in ('lambda_speed','lambda_batch','kappa_totals','events'):
            c.execute(text(f'DELETE FROM {table}'))
        c.execute(text('UPDATE checkpoints SET offset_seq=0,watermark=0'))
        if engine.dialect.name=='sqlite':c.execute(text("DELETE FROM sqlite_sequence WHERE name='events'"))
        else:c.execute(text('ALTER TABLE events ALTER COLUMN seq RESTART WITH 1'))

def generate(n,seed=2026):
    rng=random.Random(seed)
    return [dict(event_id=f'demo-{seed}-{i:07}',plate=f'TST-{i%100:03}',
         day=(date(2026,10,1)+timedelta(days=i%28)).isoformat(),
         odometer=100000+i*31,gallons_milli=rng.randint(5000,60000),
         cost_cents=rng.randint(10000,120000)) for i in range(n)]

def append(rows):
    if not rows:return 0
    with write() as c:
        # Serialize the append transaction so sequence order is also commit order.
        # Consumers must never skip an earlier sequence committed later.
        if engine.dialect.name=='postgresql': c.execute(text('SELECT pg_advisory_xact_lock(726011)'))
        before=c.execute(text('SELECT COUNT(*) FROM events')).scalar_one()
        # Preserve the first event for a duplicate ID, even if a later payload differs.
        c.execute(text('''INSERT INTO events(event_id,plate,day,odometer,gallons_milli,cost_cents)
        VALUES (:event_id,:plate,:day,:odometer,:gallons_milli,:cost_cents)
        ON CONFLICT(event_id) DO NOTHING'''),rows)
        return c.execute(text('SELECT COUNT(*) FROM events')).scalar_one()-before

def _batch(c,high):
    c.execute(text('DELETE FROM lambda_batch'))
    c.execute(text('''INSERT INTO lambda_batch SELECT plate,day,COUNT(*),SUM(gallons_milli),SUM(cost_cents)
      FROM events WHERE seq<=:hi GROUP BY plate,day'''),{'hi':high})
    c.execute(text('DELETE FROM lambda_speed WHERE seq<=:hi'),{'hi':high})
    c.execute(text("UPDATE checkpoints SET watermark=:hi WHERE mode='lambda'"),{'hi':high})

def step(mode,chunk=1000,batch_interval=10000):
    if mode not in MODES:raise ValueError('Arquitectura inválida')
    with write() as c:
        # Lock each checkpoint on PostgreSQL. SQLite deployment has one consumer per mode.
        suffix=' FOR UPDATE' if engine.dialect.name=='postgresql' else ''
        cp=c.execute(text('SELECT offset_seq,watermark FROM checkpoints WHERE mode=:m'+suffix),{'m':mode}).one()
        ids=c.execute(text('SELECT seq FROM events WHERE seq>:lo ORDER BY seq LIMIT :lim'),{'lo':cp[0],'lim':chunk}).all()
        if not ids:return 0
        high=ids[-1][0]; args={'lo':cp[0],'hi':high}
        if mode=='lambda':
            c.execute(text('''INSERT INTO lambda_speed SELECT seq,plate,day,gallons_milli,cost_cents
              FROM events WHERE seq>:lo AND seq<=:hi'''),args)
            if high-cp[1]>=batch_interval:_batch(c,high)
        else:
            c.execute(text('''INSERT INTO kappa_totals(plate,day,n,gallons_milli,cost_cents)
              SELECT plate,day,COUNT(*),SUM(gallons_milli),SUM(cost_cents) FROM events
              WHERE seq>:lo AND seq<=:hi GROUP BY plate,day
              ON CONFLICT(plate,day) DO UPDATE SET n=kappa_totals.n+excluded.n,
              gallons_milli=kappa_totals.gallons_milli+excluded.gallons_milli,
              cost_cents=kappa_totals.cost_cents+excluded.cost_cents'''),args)
        c.execute(text('UPDATE checkpoints SET offset_seq=:hi WHERE mode=:m'),{'hi':high,'m':mode})
        return len(ids)

def drain(mode):
    while step(mode):pass

def rebuild(mode):
    """Reprocesar con consumidores detenidos. Kappa reutiliza exactamente step()."""
    if mode not in MODES:raise ValueError('Arquitectura inválida')
    with write() as c:
        if mode=='lambda':
            high=c.execute(text('SELECT COALESCE(MAX(seq),0) FROM events')).scalar_one()
            _batch(c,high)
            c.execute(text("UPDATE checkpoints SET offset_seq=:hi WHERE mode='lambda'"),{'hi':high})
        else:
            c.execute(text('DELETE FROM kappa_totals'))
            c.execute(text("UPDATE checkpoints SET offset_seq=0,watermark=0 WHERE mode='kappa'"))
    if mode=='kappa':drain(mode)

def totals(mode,plate=None,start=None,end=None):
    if mode not in MODES:raise ValueError('Arquitectura inválida')
    source='SELECT * FROM kappa_totals' if mode=='kappa' else '''
    SELECT plate,day,n,gallons_milli,cost_cents FROM lambda_batch UNION ALL
    SELECT plate,day,1 AS n,gallons_milli,cost_cents FROM lambda_speed'''
    filters=[];args={}
    for key,op,value in [('plate','=',plate),('day','>=',start),('day','<=',end)]:
        if value is not None:
            name='p'+str(len(args)); filters.append(f'{key}{op}:{name}');args[name]=value
    where=' WHERE '+' AND '.join(filters) if filters else ''
    with engine.connect() as c:
        rows=c.execute(text(f'''SELECT plate,SUM(n) AS records,SUM(gallons_milli) AS gallons_milli,
          SUM(cost_cents) AS cost_cents FROM ({source}) AS source {where} GROUP BY plate ORDER BY plate'''),args).mappings().all()
    return [dict(plate=r['plate'],records=int(r['records']),gallonsMilli=int(r['gallons_milli']),costCents=int(r['cost_cents'])) for r in rows]

def expected(rows,plate=None,start=None,end=None):
    seen={};out={}
    for r in rows:seen.setdefault(r['event_id'],r)
    for r in seen.values():
        if plate and r['plate']!=plate:continue
        if start and r['day']<start:continue
        if end and r['day']>end:continue
        a=out.setdefault(r['plate'],dict(plate=r['plate'],records=0,gallonsMilli=0,costCents=0))
        a['records']+=1;a['gallonsMilli']+=r['gallons_milli'];a['costCents']+=r['cost_cents']
    return [out[p] for p in sorted(out)]
